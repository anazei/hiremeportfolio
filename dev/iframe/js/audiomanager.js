/*
    Persistent Web Audio Manager

    Designed for iOS, Android and desktop browsers.
    Initialize once in the persistent parent document.

    Call music.unlock() directly from the first
    user click or touch handler.

    All songs share the same AudioContext.
*/

class AudioManager {

    constructor(fftSize = 1024) {

        const Context = window.AudioContext ||
                        window.webkitAudioContext;

        if (!Context) {
            throw new Error("Web Audio API unavailable");
        }

        this.ctx = new Context();
        this.tracks = new Map();
        this.currentTrack = null;

        // Shared analyser for all audio tracks
        this.analyser = this.ctx.createAnalyser();
        this.analyser.smoothingTimeConstant = 0.6;

        this.setFFTSize(fftSize);

        this.analyser.connect(this.ctx.destination);

        this._request = 0;
    }

    // Unlock the persistent AudioContext on iOS
    unlock() {

        if (this.ctx.state === "closed") {
            return Promise.reject(
                new Error("AudioContext is closed")
            );
        }

        if (this.ctx.state === "running") {
            return Promise.resolve();
        }

        const resumed = this.ctx.resume();

        // Play a silent buffer during the user gesture
        // for compatibility with older iOS versions

        const source = this.ctx.createBufferSource();

        source.buffer = this.ctx.createBuffer(
            1, 1, this.ctx.sampleRate
        );

        source.connect(this.ctx.destination);

        source.onended = () => source.disconnect();

        source.start(0);

        return resumed;
    }

    // Download and decode audio into memory
    load(id, url, loop = false) {

        if (this.tracks.has(id)) {
            return this.tracks.get(id).ready;
        }

        const gain = this.ctx.createGain();

        gain.gain.value = 0;
        gain.connect(this.analyser);

        const track = {

            id,
            url,
            loop,
            gain,

            buffer: null,
            source: null,

            offset: 0,
            startedAt: 0,

            timer: null,
            callbacks: new Set(),

            version: 0
        };

        this.tracks.set(id, track);

        track.ready = (async () => {

            const response = await fetch(url, {
                mode: "cors"
            });

            if (!response.ok) {

                throw new Error(
                    `Audio download failed: ${response.status} ${url}`
                );
            }

            track.buffer = await this.ctx.decodeAudioData(
                await response.arrayBuffer()
            );

            return track;

        })().catch(error => {

            if (this.tracks.get(id) === track) {
                this.tracks.delete(id);
            }

            gain.disconnect();

            throw error;
        });

        // Prevent unhandled rejection when legacy
        // callers ignore the return value of load()

        track.ready.catch(error => console.error(error));

        return track.ready;
    }

    // Retrieve a track
    getTrack(id) {

        const track = this.tracks.get(id);

        if (!track) {
            console.warn("Track not found:", id);
        }

        return track || null;
    }

    // Cancel scheduled fades and timers
    cancelFade(track) {

        clearTimeout(track.timer);

        track.timer = null;

        const param = track.gain.gain;
        const now = this.ctx.currentTime;

        if (typeof param.cancelAndHoldAtTime === "function") {

            param.cancelAndHoldAtTime(now);

        } else {

            const value = param.value;

            param.cancelScheduledValues(now);
            param.setValueAtTime(value, now);
        }
    }

    // Internal method: stop a source while
    // optionally preserving its playback position
    _halt(track, reset = false) {

        this.cancelFade(track);

        if (track.source) {

            const source = track.source;

            const elapsed = Math.max(
                0,
                this.ctx.currentTime - track.startedAt
            );

            const duration = track.buffer.duration;

            track.offset = track.loop
                ? (track.offset + elapsed) % duration
                : Math.min(duration, track.offset + elapsed);

            track.source = null;

            source.onended = null;

            try {
                source.stop();
            } catch (_) {}

            source.disconnect();
        }

        if (reset) {
            track.offset = 0;
        }

        track.gain.gain.setValueAtTime(
            0,
            this.ctx.currentTime
        );

        if (this.currentTrack === track.id) {
            this.currentTrack = null;
        }
    }

    // Internal method: create and start an audio source
    _start(track) {

        if (track.source) return;

        if (track.offset >= track.buffer.duration) {
            track.offset = 0;
        }

        const source = this.ctx.createBufferSource();

        source.buffer = track.buffer;
        source.loop = track.loop;

        source.connect(track.gain);

        track.source = source;
        track.startedAt = this.ctx.currentTime;

        source.onended = () => {

            if (track.source !== source) return;

            source.disconnect();

            track.source = null;
            track.offset = 0;

            this.cancelFade(track);

            if (this.currentTrack === track.id) {
                this.currentTrack = null;
            }

            for (const callback of track.callbacks) {

                try {
                    callback(track.id);
                } catch (error) {
                    console.error(error);
                }
            }
        };

        source.start(0, track.offset);
    }

    // Internal playback method shared by play,
    // restart, fadeIn and crossFade
    async _play(id, duration, reset, crossfade) {

        const track = this.getTrack(id);

        if (!track) return;

        const request = ++this._request;
        const version = ++track.version;

        // Resume the existing AudioContext immediately.
        // Do not create a new AudioContext.

        await Promise.all([

            this.ctx.state === "running"
                ? Promise.resolve()
                : this.unlock(),

            track.ready

        ]);

        // Prevent outdated asynchronous playback requests
        // from starting tracks unexpectedly

        if (request !== this._request ||
            version !== track.version) {

            return;
        }

        const oldId = this.currentTrack;

        if (reset) {
            this._halt(track, true);
        }

        this.cancelFade(track);

        const now = this.ctx.currentTime;

        const seconds = Math.max(
            0,
            Number(duration) || 0
        );

        track.gain.gain.setValueAtTime(
            seconds ? 0 : 1,
            now
        );

        this._start(track);

        if (seconds) {

            track.gain.gain.linearRampToValueAtTime(
                1,
                now + seconds
            );
        }

        if (crossfade &&
            oldId !== null &&
            oldId !== id) {

            this.fadeOut(oldId, seconds);
        }

        this.currentTrack = id;
    }

    // Play a track immediately
    play(id) {

        return this._play(id, 0, false, false);
    }

    // Restart a track from the beginning
    restart(id) {

        return this._play(id, 0, true, false);
    }

    // Fade in a track
    fadeIn(id, duration = 2) {

        return this._play(id, duration, false, false);
    }

    // Crossfade from the current track to another track
    crossFade(id, duration = 3) {

        if (this.currentTrack === id) {
            return Promise.resolve();
        }

        return this._play(id, duration, true, true);
    }

    // Fade out a track smoothly
    fadeOut(id, duration = 2) {

        const track = this.getTrack(id);

        if (!track) return;

        ++track.version;

        this.cancelFade(track);

        const seconds = Math.max(
            0,
            Number(duration) || 0
        );

        if (!seconds || !track.source) {

            this._halt(track);

            return;
        }

        const now = this.ctx.currentTime;
        const gain = track.gain.gain;
        const initial = gain.value;

        // Approximate a quadratic fade using linear ramps.
        // This allows fades to be interrupted on older Safari.

        gain.setValueAtTime(initial, now);

        for (let i = 1; i <= 32; i++) {

            const t = i / 32;

            gain.linearRampToValueAtTime(
                initial * (1 - t) ** 2,
                now + seconds * t
            );
        }

        const end = now + seconds;

        const finish = () => {

            // Follow the AudioContext clock instead of
            // relying exclusively on wall-clock time.

            const remaining = end - this.ctx.currentTime;

            if (remaining > 0.015) {

                track.timer = setTimeout(
                    finish,
                    Math.max(50, remaining * 1000)
                );

                return;
            }

            this._halt(track);
        };

        track.timer = setTimeout(
            finish,
            seconds * 1000
        );
    }

    // Stop immediately, preserving playback position
    stop(id) {

        const track = this.getTrack(id);

        if (!track) return;

        ++track.version;

        this._halt(track);
    }

    // Set volume between 0 and 1
    setVolume(id, volume) {

        const track = this.getTrack(id);

        if (!track) return;

        this.cancelFade(track);

        track.gain.gain.setValueAtTime(

            Math.max(0, Math.min(1, volume)),

            this.ctx.currentTime
        );
    }

    // Get frequency bins (0-255)
    getBins() {

        this.analyser.getByteFrequencyData(this.bins);

        return this.bins;
    }

    // Get waveform data (0-255)
    getWaveform() {

        this.analyser.getByteTimeDomainData(
            this.waveform
        );

        return this.waveform;
    }

    // Get average frequency magnitude (0-255)
    getAverageVolume() {

        const bins = this.getBins();

        let sum = 0;

        for (let i = 0; i < bins.length; i++) {

            sum += bins[i];
        }

        return sum / bins.length;
    }

    // Change FFT size
    setFFTSize(size) {

        this.analyser.fftSize = size;

        this.bins = new Uint8Array(
            this.analyser.frequencyBinCount
        );

        this.waveform = new Uint8Array(
            this.analyser.fftSize
        );
    }

    // Listen for when a track finishes naturally
    onEnded(id, callback) {

        const track = this.getTrack(id);

        if (track) {
            track.callbacks.add(callback);
        }
    }

    // Unload a track and release its decoded audio
    // without closing the persistent AudioContext
    unload(id) {

        const track = this.tracks.get(id);

        if (!track) return;

        ++track.version;

        this._halt(track, true);

        track.gain.disconnect();

        this.tracks.delete(id);
    }

} //end class

  /*  API

    Initialize and load tracks:

    var music = new AudioManager();
    music.load("song1", "audio/song1.mp3", true); //boolean is whether to loop
    music.load("song2", "audio/song2.mp3", true); //boolean is whether to loop

    Play immediately	music.play("song1")
    Fade in over 2 seconds	music.fadeIn("song1", 2)
    Fade out over 3 seconds	music.fadeOut("song1", 3)
    Crossfade to song 2	music.crossFade("song2", 3)
    Set volume to 50%	music.setVolume("song1", 0.5)
    Stop immediately	music.stop("song1")

    music.getBins() — returns a Uint8Array of frequency values (0–255).
    music.getWaveform() — returns waveform samples (0–255).
    music.getAverageVolume() — returns average frequency magnitude (0–255).
    music.setFFTSize(2048) — configures the frequency resolution.

  */
