/*
    I wrote this buffering animation in 2015
    The scale sizes of five circle follow a differnt point of a single sine wave value over infinitely
*/
(function(window){

  var slideRuleArray;
  var circleArray;
  var circle;
  var counter = 0;
  var bufferingText;
  var stage;
  var runAnimation = true;
  var timer;

  const CIRCLE_RADIUS = 50;
  const CIRCLE_COLOUR = "#FFFFFF";
  const NUM_CIRCLES = 5;
  const KEVINS_MAGIC_CONSTANT = .9; //this constant was generated by (Math.PI/180 * 52) and rounded off to 0.9, multiplying it by 53 changes the animation gradually

  function BufferAnimation(canvasName)
  {
      init(canvasName);
      this.stopAnimation();
  }

  function init(canvasName)
  {
      slideRuleArray = new Array();
      circleArray = new Array();
      stage = new createjs.Stage(canvasName);

      //generate and store the circles for animation
      for(var i=0;i<NUM_CIRCLES;i++)
      {
        circle = new createjs.Shape();
        circle.graphics.beginFill(CIRCLE_COLOUR).drawCircle(0, 0, CIRCLE_RADIUS);
        circle.scaleX = circle.scaleY = 0;
        circle.x = (i * 35) + 50;
        circle.y = CIRCLE_RADIUS/2;
        circleArray[i] = circle;
        stage.addChild(circle);

        //this will precompute all the values into a multidimensional array lookup table so no cosine calculations are needed in real time
        slideRuleArray[i] = new Array(180);
        for(var j=0;j<180;j++)
        {
            slideRuleArray[i][j] = Math.cos((j + i * KEVINS_MAGIC_CONSTANT) * 10) / 5;
        }
      }

      bufferingText = new createjs.Text("Loading...", "12px Arial", CIRCLE_COLOUR) ;
      bufferingText.x = 100;
      bufferingText.y = CIRCLE_RADIUS + 15;
      bufferingText.textBaseline = "alphabetic";
      stage.addChild(bufferingText);
      stage.update();
    }

    function animateCircle()
    {
      if(runAnimation == true)
      {
        var circleArrayLength = circleArray.length;

        for(var i=0;i<circleArrayLength;i++)
        {
            circleArray[i].scaleX = circleArray[i].scaleY = slideRuleArray[i][counter % 180]
        }

        counter = (counter + 5) % 180;
        stage.update();
      }
    }

    BufferAnimation.prototype.startAnimation = function()
    {
        runAnimation = true;
        stage.addChild(bufferingText);
        stage.update();
        timer = setInterval(animateCircle, 50);
    }

    BufferAnimation.prototype.stopAnimation = function()
    {
        runAnimation = false;
        counter = 0;
        stage.removeChild(bufferingText);
        stage.update();
        clearInterval(timer);
    }

  window.BufferAnimation = BufferAnimation;

}(window) );
